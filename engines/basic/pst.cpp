int pieceSquareValue(Style style, PieceType type, Square square) {
  const int rank = rankOf(square) - 1;
  // 9 筋を左端 (添字 0) として並べているため、筋を反転して参照する。
  const int file = FILE_COUNT - fileOf(square);
  const bool ranging = style == STYLE_RANGING_ROOK;
  switch (type) {
    case KING:
      return ranging ? KING_RANGING[rank][file] : KING_STATIC[rank][file];
    case ROOK:
      return ranging ? ROOK_RANGING[rank][file] : ROOK_STATIC[rank][file];
    case BISHOP:
      return ranging ? BISHOP_RANGING[rank][file] : BISHOP_STATIC[rank][file];
    case GOLD:
      return ranging ? GOLD_RANGING[rank][file] : GOLD_STATIC[rank][file];
    case SILVER:
      return ranging ? SILVER_RANGING[rank][file] : SILVER_STATIC[rank][file];
    case PAWN:
      return ranging ? PAWN_STATIC[rank][file] : PAWN_RANGING[rank][file];
    case LANCE:
      return LANCE_TABLE[rank][file];
    case KNIGHT:
      return KNIGHT_TABLE[rank][file];
    case PROM_PAWN:
    case PROM_LANCE:
    case PROM_KNIGHT:
    case PROM_SILVER:
      return PROMOTED_GOLD_TABLE[rank][file];
    case HORSE:
    case DRAGON:
    default:
      return 0;
  }
}

